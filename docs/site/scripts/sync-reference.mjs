#!/usr/bin/env node
// Copy the repository's own documentation into the site, once, before every
// `dev` and `build`.
//
// Those files in `docs/` are written for the owner and for the agent, and they
// stay where they are: they are read from a terminal and from a pull request as
// often as from a browser. The site shows the same text rather than a second
// copy of it that drifts, so this script is the only place the two meet.
//
// What it does to each file:
//   - takes the first `# ` heading as the page title and removes that line,
//     because Starlight draws the title itself from the frontmatter;
//   - writes a frontmatter block saying where the file came from;
//   - rewrites links between the copied files so they still work from their
//     new folder, and says so out loud when a link points at something that
//     was not copied.
//
// The output folder is generated and is not committed. Nothing here edits a
// file under `docs/` — if a reference page reads badly, the fix belongs in the
// original.

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = resolve(siteDir, '..', '..');
const outDir = join(siteDir, 'src', 'content', 'docs', 'reference');

// The order here is the order of the Reference section in the sidebar.
const pages = [
  {
    file: 'running.md',
    description: 'Running the app on your laptop, on the server, and after a disaster.',
  },
  { file: 'backups.md', description: 'The two copies of your data, and how to prove they work.' },
  {
    file: 'cost.md',
    description: 'What the subscription, the server and the rest cost per month.',
  },
  {
    file: 'glossary.md',
    description: 'Every technical word this documentation uses, in five words each.',
    // It has its own top-level place in the sidebar, so it stays out of the
    // Reference group rather than appearing in both.
    hidden: true,
  },
  {
    file: 'agents.md',
    description: 'The settings that live on your own computer rather than in the project.',
  },
  {
    file: 'stack.md',
    description: 'Every piece the app is built from, the version, and why that one.',
  },
  { file: 'decisions.md', description: 'What was decided while shaping the kit, and why.' },
];

const known = new Set(pages.map((page) => page.file));

/** YAML needs a quoted string, and a quote inside it needs doubling. */
function quote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

/** Take the first `# Heading` line out of the body and return it as the title. */
function takeTitle(body, file) {
  const match = body.match(/^#[ \t]+(.+?)[ \t]*$/m);
  if (!match) throw new Error(`${file} has no '# ' heading, so the page would have no title`);
  const stripped = body.slice(0, match.index) + body.slice(match.index + match[0].length);
  return { title: match[1], body: stripped.replace(/^\s+/, '') };
}

/**
 * Links between the copied files keep working because the files stay in one
 * folder together; `docs/backups.md` and `./backups.md` are both normalised to
 * the same shape so the source can write either. A link to a repository file
 * that is not part of the set cannot resolve from a browser, so it is reported
 * and left alone rather than silently pointed somewhere wrong.
 */
function rewriteLinks(body, file, warnings) {
  return body.replace(/\]\(([^)\s]+?\.md)(#[^)\s]*)?\)/g, (whole, target, anchor = '') => {
    const name = target.replace(/^\.?\/?/, '').replace(/^docs\//, '');
    if (known.has(name)) return `](./${name}${anchor})`;
    warnings.push(`${file}: link to ${target}, which is not one of the copied pages`);
    return whole;
  });
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const warnings = [];
for (const [index, page] of pages.entries()) {
  const source = join(repoDir, 'docs', page.file);
  const raw = readFileSync(source, 'utf8');
  const { title, body } = takeTitle(raw, page.file);
  const frontmatter = [
    '---',
    `title: ${quote(title)}`,
    `description: ${quote(page.description)}`,
    'sidebar:',
    `  order: ${index + 1}`,
    ...(page.hidden ? ['  hidden: true'] : []),
    `editUrl: ${quote(`https://github.com/brocoders/inhouse-ai-starter-kit/edit/main/docs/${page.file}`)}`,
    '---',
    '',
    `<!-- Generated by docs/site/scripts/sync-reference.mjs from docs/${page.file}. Do not edit. -->`,
    '',
  ].join('\n');
  writeFileSync(join(outDir, page.file), frontmatter + rewriteLinks(body, page.file, warnings));
}

for (const warning of warnings) console.warn(`sync-reference: ${warning}`);
console.log(
  `sync-reference: copied ${pages.length} pages into ${outDir.replace(siteDir + '/', '')}` +
    ` (${readdirSync(outDir).length} files)`,
);
