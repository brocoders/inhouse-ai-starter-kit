#!/usr/bin/env node
// The deterministic half of the design system (frontend/DESIGN.md). Everything
// a script can decide is decided here so that review can be about judgment.
// Dependency-free Node, like every checker in this kit.
//
//   node scripts/check-frontend.mjs
//
// Source rules always run. The bundle budget runs only when dist/frontend
// exists, which it does inside `pnpm check` because the frontend is built
// there first.
//
// Each rule below exists because something it forbids broke a real screen.
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import path from 'node:path';

export const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = 'frontend/src';
const FORMAT = `${SRC}/lib/format.ts`;
const CHARTS = `${SRC}/components/charts/`;
const VOCABULARY = `${SRC}/components/inhouse/`;
const UI = `${SRC}/components/ui/`;
// Generated by the router plugin, rewritten on every route change, and not
// ours to obey rules about.
const GENERATED = `${SRC}/routeTree.gen.ts`;
// Two budgets, measured from the built chunks, both gzipped.
//
// "Before any screen" is the shell — everything the entry imports statically
// — plus what two or more screens share, which Vite splits out of the shell
// but every first visit downloads anyway (the vocabulary, the API client,
// the query cache). "One screen's own" is what a single screen loads that no
// other screen and not the shell does: the number that grows when a screen
// gets heavy, and the one the first real app could not see when a single
// 200 KB ceiling was hit on day three with "10 bytes left". The heavy screen
// is named. Pieces a screen loads on demand (a chart, a sheet) are outside
// both; the one rule for them is that the chart library never reaches the
// shell.
export const BEFORE_ANY_SCREEN_BUDGET_GZIP = 280 * 1024;
export const SCREEN_OWN_BUDGET_GZIP = 60 * 1024;

const HEX = /#[0-9a-fA-F]{6}(?![0-9a-zA-Z])|#[0-9a-fA-F]{3}(?![0-9a-zA-Z_-])/;
// Tailwind's own palette is a colour outside the tokens as much as a hex value
// is; warnings use `warning`, deltas `positive`/`negative`, series `chart-*`.
const PALETTE_COLOURS =
  'amber|emerald|red|blue|green|yellow|gray|grey|slate|zinc|neutral|stone|orange|lime|teal|cyan|sky|indigo|violet|purple|fuchsia|pink|rose';
const PALETTE = new RegExp(
  `\\b(?:text|bg|border|ring|fill|stroke|from|to|via|outline|decoration|shadow|accent|caret|divide)-(?:${PALETTE_COLOURS})-\\d+\\b`,
);
// Dark mode is a token swap in index.css: every token has a dark value, so a
// component that names a colour for dark mode is deciding twice and the two
// decisions drift. A `dark:` variant on a colour utility is always that.
const DARK_VARIANT = new RegExp(
  `\\bdark:(?:text|bg|border|ring|fill|stroke|from|to|via|outline|decoration|shadow|accent|caret|divide)-[A-Za-z[]`,
);
const RECHARTS_IMPORT = /from\s+['"]recharts/;
const INTL = /\bIntl\.[A-Z]/;
// A dialog and a bottom sheet are both fixed and neither scrolls the page
// behind it, so one taller than the screen cannot be reached at either end.
// The primitives come from the registry and are never edited, so the bound
// belongs on the call.
const OVERLAY = /<(?:Dialog|Sheet)Content\b[^>]*>/gs;
// Words a person reads, typed straight into JSX: `>Save<`. Every such string
// goes through t() so the app has one place its language lives. A heuristic:
// text between a tag's `>` and the next `<` with two or more letters, and none
// of the characters that mean it is code rather than prose (`=>` is not a tag
// end; `{…}` is an expression, which is where t() already sits; `&&` and `||`
// are a condition, not a sentence).
const JSX_TEXT = /(?<![=\-])>([^<>{}();=&|]*[A-Za-z][^<>{}();=&|]*[A-Za-z][^<>{}();=&|]*)</g;
const TRANSLATED = [`${SRC}/routes/`, VOCABULARY];
// Where a finger lands: a row, a link or a button in a screen, a primitive or
// the shell. DESIGN.md asks for 44 px on the phone, which is `min-h-11`; a
// smaller height is fine for the desktop behind `sm:` or `md:`, never bare.
// The sidebar is the one exception — the whole column is hidden under `md`.
const TOUCHED = [`${SRC}/routes/`, VOCABULARY, `${SRC}/components/shell/`];
const DESKTOP_ONLY = [`${SRC}/components/shell/app-sidebar.tsx`];
const TARGET_TAG = /<(?:li|a|Link|button|Button)\b[^>]*?className="([^"]*)"[^>]*>/gs;
const BARE_HEIGHT = /(?:^|\s)(?:min-)?(?:h|size)-(\d+)(?=\s|$)/g;
const MIN_TOUCH_UNITS = 11;

const lineOf = (text, index) => text.slice(0, index).split('\n').length;

/**
 * Every source rule, for one file. `rel` is the repository-relative POSIX path,
 * which is what decides the exemptions, so tests can pass fixture strings.
 */
export function checkSourceFile(rel, text) {
  const errors = [];
  if (rel === GENERATED) return errors;
  const isUi = rel.startsWith(UI);
  const isChart = rel.startsWith(CHARTS);
  const isVocabulary = rel.startsWith(VOCABULARY);

  text.split('\n').forEach((line, i) => {
    const at = `${rel}:${i + 1}`;
    if (!isUi && HEX.test(line) && !line.includes('href="#')) {
      errors.push(`${at}: raw colour; use a token from index.css`);
    }
    if (!isUi && PALETTE.test(line)) {
      errors.push(
        `${at}: palette colour class; use a token (warning, positive, negative, chart-*)`,
      );
    }
    if (!isUi && DARK_VARIANT.test(line)) {
      errors.push(
        `${at}: dark: colour class; dark mode is a token swap in index.css, not a second set of classes`,
      );
    }
  });

  // lib/i18n.ts may use Intl.PluralRules: choosing a plural form is the
  // translation layer's job. Dates, numbers and money stay in lib/format.ts.
  const intlOutsideFormat =
    rel === `${SRC}/lib/i18n.ts`
      ? /\bIntl\.(?!PluralRules|LDMLPluralRule)[A-Z]/.test(text)
      : INTL.test(text);
  if (intlOutsideFormat && rel !== FORMAT) {
    errors.push(`${rel}: Intl belongs in lib/format.ts; the app has one time zone and one locale`);
  }
  if (RECHARTS_IMPORT.test(text) && !isChart) {
    errors.push(
      `${rel}: recharts may only be imported inside components/charts/ so it stays out of the first paint`,
    );
  }
  if (/components\/ui\/select['"]/.test(text) && !isVocabulary) {
    errors.push(
      `${rel}: pick from a list with the Choice component (components/inhouse), not a raw Select`,
    );
  }
  if (!isUi && /<table\b/.test(text)) {
    errors.push(
      `${rel}: raw <table>; use the Table primitive or card rows, which have the phone layout`,
    );
  }
  if (!isUi) {
    for (const opening of text.matchAll(OVERLAY)) {
      const tag = opening[0];
      if (tag.includes('max-h-') && tag.includes('overflow-y-auto')) continue;
      errors.push(
        `${rel}:${lineOf(text, opening.index)}: dialog and sheet content needs max-h-[90dvh] overflow-y-auto; ` +
          'it is fixed, so content taller than the screen cannot be scrolled to',
      );
    }
  }
  if (!isUi && TRANSLATED.some((dir) => rel.startsWith(dir)) && rel.endsWith('.tsx')) {
    for (const m of text.matchAll(JSX_TEXT)) {
      const words = m[1].trim().replace(/\s+/g, ' ');
      errors.push(
        `${rel}:${lineOf(text, m.index)}: "${words.length > 40 ? words.slice(0, 40) + '…' : words}" ` +
          'is typed into the screen; put it in the dictionary and render it with t()',
      );
    }
  }
  if (
    rel.endsWith('.tsx') &&
    TOUCHED.some((dir) => rel.startsWith(dir)) &&
    !DESKTOP_ONLY.includes(rel)
  ) {
    for (const tag of text.matchAll(TARGET_TAG)) {
      for (const height of tag[1].matchAll(BARE_HEIGHT)) {
        if (Number(height[1]) >= MIN_TOUCH_UNITS) continue;
        errors.push(
          `${rel}:${lineOf(text, tag.index)}: "${height[0].trim()}" on a row, link or button is under 44 px; ` +
            'on the phone it needs min-h-11 or more, with the desktop height behind sm: (DESIGN.md, Space and density)',
        );
      }
    }
  }
  // Base UI's Button renders type="button", so a form's Button submits nothing
  // unless it says type="submit" — a save button that did nothing at all.
  const forms = text.split('<form').length - 1;
  if (forms && text.split('type="submit"').length - 1 < forms) {
    errors.push(
      `${rel}: ${forms} <form> but fewer type="submit" buttons; a Button submits only with type="submit"`,
    );
  }
  return errors;
}

// With a locale named. Bare localeCompare sorts by whatever locale the
// machine happens to have, so the order of findings differed between a
// laptop and CI on the first real project; one locale, the same everywhere.
export const byName = (a, b) => a.name.localeCompare(b.name, 'en');

function sourceFiles(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort(byName)) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, out);
    else if (/\.tsx?$/.test(entry.name) && !entry.name.endsWith('.d.ts')) out.push(full);
  }
  return out;
}

export function sourceRules(root = ROOT) {
  const src = path.join(root, SRC);
  if (!existsSync(src)) {
    console.log('check-frontend: no frontend/src yet, source rules skipped');
    return [];
  }
  const errors = [];
  for (const file of sourceFiles(src)) {
    const rel = path.relative(root, file).split(path.sep).join('/');
    errors.push(...checkSourceFile(rel, readFileSync(file, 'utf8')));
  }
  return errors;
}

const STATIC_IMPORT = /from\s*["']\.\/([A-Za-z0-9_.-]+\.js)["']/g;
const DYNAMIC_IMPORT = /import\(\s*["'`]\.\/([A-Za-z0-9_.-]+\.js)["'`]\s*\)/g;
const kb = (bytes) => Math.round(bytes / 1024);
// "items-BoaAisiZ.js" is the items screen; the hash is noise to a reader.
const pieceName = (file) => file.replace(/-[A-Za-z0-9_-]{8}\.js$/, '').replace(/\.js$/, '');

/**
 * Everything reached from `start` through static imports, leaving out the
 * chunks in `already` (the shell, when measuring a screen). Also collects the
 * dynamic imports met on the way, which are the screens and lazy pieces.
 */
function closure(start, assets, already = new Set()) {
  const chunks = new Set();
  const dynamic = new Set();
  const queue = [...start];
  let bytes = 0;
  let recharts = [];
  while (queue.length) {
    const name = queue.pop();
    if (chunks.has(name) || already.has(name)) continue;
    const chunk = path.join(assets, name);
    if (!existsSync(chunk)) continue;
    chunks.add(name);
    const content = readFileSync(chunk);
    bytes += gzipSync(content).length;
    const text = content.toString('utf8');
    if (text.includes('recharts')) recharts.push(name);
    for (const m of text.matchAll(STATIC_IMPORT)) queue.push(m[1]);
    for (const m of text.matchAll(DYNAMIC_IMPORT)) dynamic.add(m[1]);
  }
  return { chunks, bytes, recharts, dynamic };
}

/**
 * The shell is what index.html's entry reaches by static imports; it must
 * not carry the chart library. Each dynamic import met in the shell is a
 * screen; its static closure beyond the shell is split into what it shares
 * with another screen and what is its own. Shell plus shared is "before any
 * screen"; each screen's own weight is held to the screen budget.
 */
export function bundleRules(root = ROOT) {
  const built = path.join(root, 'dist', 'frontend');
  const indexHtml = path.join(built, 'index.html');
  if (!existsSync(indexHtml) || !statSync(indexHtml).isFile()) {
    console.log('check-frontend: no build in dist/frontend, bundle budget skipped');
    return [];
  }
  const html = readFileSync(indexHtml, 'utf8');
  const entries = [...html.matchAll(/<script[^>]*\bsrc="\/assets\/([^"]+\.js)"/g)].map((m) => m[1]);
  if (!entries.length)
    return ['dist/frontend/index.html: no entry script found; did the build change its output?'];

  const assets = path.join(built, 'assets');
  const errors = [];
  const shell = closure(entries, assets);
  for (const name of shell.recharts) {
    errors.push(
      `dist/frontend/assets/${name}: carries Recharts and is reached from the entry's static imports`,
    );
  }

  const screens = new Map();
  for (const file of shell.dynamic) screens.set(file, closure([file], assets, shell.chunks));
  const reachedBy = new Map();
  for (const screen of screens.values()) {
    for (const chunk of screen.chunks) reachedBy.set(chunk, (reachedBy.get(chunk) ?? 0) + 1);
  }
  const sizeOf = (chunk) => gzipSync(readFileSync(path.join(assets, chunk))).length;
  let shared = 0;
  for (const [chunk, count] of reachedBy) if (count > 1) shared += sizeOf(chunk);

  const beforeAnyScreen = shell.bytes + shared;
  if (beforeAnyScreen > BEFORE_ANY_SCREEN_BUDGET_GZIP) {
    errors.push(
      `dist/frontend/assets: ${kb(beforeAnyScreen)} KB gzip loads before any screen ` +
        `(shell ${kb(shell.bytes)} + shared by screens ${kb(shared)}), budget ${kb(BEFORE_ANY_SCREEN_BUDGET_GZIP)} KB; ` +
        'import the heavy part lazily',
    );
  }
  let heaviest = null;
  for (const [file, screen] of screens) {
    let own = 0;
    for (const chunk of screen.chunks) if (reachedBy.get(chunk) === 1) own += sizeOf(chunk);
    if (!heaviest || own > heaviest.own) heaviest = { file, own };
    if (own > SCREEN_OWN_BUDGET_GZIP) {
      errors.push(
        `dist/frontend/assets/${file}: the "${pieceName(file)}" screen is ${kb(own)} KB gzip of its own ` +
          `on top of the shell, budget ${kb(SCREEN_OWN_BUDGET_GZIP)} KB; split what it loads or load less of it`,
      );
    }
  }
  if (!errors.length) {
    const screen = heaviest
      ? `; heaviest screen "${pieceName(heaviest.file)}" ${kb(heaviest.own)} KB of ${kb(SCREEN_OWN_BUDGET_GZIP)}`
      : '';
    console.log(
      `check-frontend: ${kb(beforeAnyScreen)} KB gzip before any screen of ${kb(BEFORE_ANY_SCREEN_BUDGET_GZIP)} ` +
        `(shell ${kb(shell.bytes)} in ${shell.chunks.size} chunk(s), shared by screens ${kb(shared)})${screen}; charts lazy`,
    );
  }
  return errors;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const errors = [...sourceRules(), ...bundleRules()];
  if (errors.length) {
    console.error(errors.join('\n'));
    console.error(
      `\n${errors.length} problem(s). Each line is file:line followed by what to do instead.`,
    );
    process.exit(2);
  }
  console.log('check-frontend: design rules hold');
}
